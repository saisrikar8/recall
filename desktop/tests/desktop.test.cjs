const { test } = require('node:test');
const assert = require('node:assert/strict');
const { _electron: electron, expect } = require('@playwright/test');
const { spawnSync } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const python = path.join(root, '.venv/bin/python');

test('desktop library, original previews, quick search, and window handoff', { timeout: 120000 }, async () => {
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'recall-desktop-test-'));
  const fixture=spawnSync(python,[path.join(__dirname,'fixture.py'),dir],{cwd:root,encoding:'utf8',env:{...process.env,PYTHONPATH:root}});
  assert.equal(fixture.status,0,fixture.stderr);
  const errors=[];
  const desktop=await electron.launch({args:[path.join(root,'desktop')],cwd:root,env:{...process.env,RECALL_DB_PATH:path.join(dir,'index.db'),RECALL_PYTHON:python,RECALL_EMBEDDING_SOCKET:path.join(dir,'unused-worker.sock'),HF_HUB_OFFLINE:'1',TRANSFORMERS_OFFLINE:'1',RECALL_DISABLE_AUTOSTART:'1',RECALL_DESKTOP_USER_DATA:path.join(dir,'electron-data')},timeout:30000});
  try {
    const page=await desktop.firstWindow();
    const clickMenu=id=>desktop.evaluate(({Menu},value)=>Menu.getApplicationMenu().getMenuItemById(value).click(),id);
    page.on('pageerror',error=>errors.push(error.message));
    await page.locator('.file-row').first().waitFor();
    assert.equal(await page.locator('.file-row').count(),4);
    await page.locator('[data-appearance="light"]').click();
    assert.equal(await page.locator('html').getAttribute('data-theme'),'light');
    await page.locator('[data-appearance="light"]').focus();
    await page.keyboard.press('Meta+k');
    assert.equal(await page.locator('#search-input').evaluate(node=>node===document.activeElement),false);
    assert.equal(await page.getByText('⌘ K',{exact:true}).count(),0);
    await page.locator('[data-appearance="dark"]').click();
    assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
    const colors=await page.locator('.sidebar').evaluate(node=>({bg:getComputedStyle(node).backgroundColor,text:getComputedStyle(node).color}));
    assert.equal(colors.bg,'rgb(20, 26, 22)');
    const settingsPromise=desktop.waitForEvent('window');
    await clickMenu('settings');
    const settings=await settingsPromise;
    await settings.getByRole('heading',{name:'Settings',exact:true}).waitFor();
    await settings.locator('#startup-toggle').uncheck();
    await expect.poll(()=>desktop.evaluate(({Menu})=>Menu.getApplicationMenu().getMenuItemById('login').checked)).toBe(false);
    await settings.locator('[data-appearance="light"]').click();
    await expect.poll(()=>page.locator('html').getAttribute('data-theme')).toBe('light');
    await clickMenu('theme-dark');
    await expect.poll(()=>settings.locator('html').getAttribute('data-theme')).toBe('dark');
    await settings.screenshot({path:'/tmp/recall-desktop-settings.png',scale:'css'});
    await settings.close();
    await page.locator('[data-collection="0"]').click();
    await expect.poll(()=>desktop.evaluate(({Menu})=>Menu.getApplicationMenu().getMenuItemById('reindex').enabled)).toBe(true);
    await clickMenu('search-collection');
    await expect.poll(()=>page.locator('#search-input').evaluate(node=>node===document.activeElement)).toBe(true);
    await clickMenu('reindex');
    await expect.poll(()=>page.locator('[data-view="home"]').getAttribute('aria-current')).toBe('page');
    await expect.poll(()=>desktop.evaluate(({Menu})=>Menu.getApplicationMenu().getMenuItemById('add-files').enabled),{timeout:60000}).toBe(true);

    await page.locator('.file-row').filter({hasText:'A note on remembering.md'}).click();
    await page.locator('.document h1').waitFor();
    assert.equal(await page.locator('.document h1').textContent(),'A note on remembering');
    await page.locator('.main').evaluate(node=>{node.scrollTop=0;});
    await page.screenshot({path:'/tmp/recall-desktop-dashboard.png',scale:'css'});
    await page.locator('.file-row').filter({hasText:'retrieval.py'}).click();
    await page.locator('.code-view').waitFor();
    assert.match(await page.locator('.code-view').textContent(),/find_memory/);
    await page.locator('.file-row').filter({hasText:'Field notes.pdf'}).click();
    await page.locator('.pdf-page img').waitFor();
    await page.getByRole('button',{name:'Next page',exact:true}).click();
    await page.getByText('Page 2 of 2',{exact:true}).waitFor();
    await page.getByRole('button',{name:'Open preview in a new window',exact:true}).click();
    const preview=await desktop.waitForEvent('window');
    await preview.getByText('Page 2 of 2',{exact:true}).waitFor();
    assert.equal(await preview.locator('html').getAttribute('data-theme'),'dark');
    await preview.screenshot({path:'/tmp/recall-desktop-preview.png'});
    await preview.close();
    assert.equal(await page.getByRole('button',{name:'Design toolkit'}).count(),0);
    assert.equal(await page.locator('[data-appearance="dark"]').getAttribute('aria-pressed'),'true');
    await page.getByRole('button',{name:'Overview',exact:true}).click();
    await desktop.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(win=>win.webContents.getURL().includes('mode=dashboard')).close());
    await expect.poll(()=>desktop.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().some(win=>win.isVisible()))).toBe(false);
    // The global shortcut handler must still be usable with the library closed.
    await page.evaluate(()=>window.recall.launcher());
    const launcher=await desktop.waitForEvent('window');
    await launcher.locator('.file-row').first().waitFor();
    assert.equal(await launcher.locator('html').getAttribute('data-theme'),'dark');
    await launcher.locator('#preview[aria-busy="false"]').waitFor();
    assert.equal(await launcher.locator('.local-card').count(),0);
    assert.equal(await launcher.locator('.row-path').count(),0);
    await launcher.screenshot({path:'/tmp/recall-desktop-launcher.png',scale:'css'});
    await launcher.locator('#search-input').fill('retrieval');
    await launcher.locator('#list-heading').filter({hasText:'SEARCH RESULTS'}).waitFor({timeout:60000});
    assert.ok(await launcher.locator('.file-row').count()>0);
    await launcher.keyboard.press('ArrowDown');
    assert.equal(await launcher.locator('.file-row.selected').count(),1);
    const newPreviewPromise=desktop.waitForEvent('window');
    await launcher.keyboard.press('Enter');
    const newPreview=await newPreviewPromise;
    await newPreview.locator('#preview[aria-busy="false"]').waitFor();
    await expect.poll(()=>desktop.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(win=>win.webContents.getURL().includes('mode=launcher')).isVisible())).toBe(false);
    await newPreview.close();
    await page.locator('#search-input').fill('retrieval');
    await page.locator('#search-form').evaluate(form=>form.requestSubmit());
    await page.locator('#list-heading').filter({hasText:'SEARCH RESULTS'}).waitFor({timeout:60000});
    await page.locator('#preview[aria-busy="false"]').waitFor();
    assert.ok(await page.locator('.row-excerpt mark').count()>0);
    const progress = await page.evaluate(async()=>{
      const {renderIndexProgress}=await import('./app.js');
      renderIndexProgress({messages:['[1/3] Checking a.py']},1,1,'/tmp/notes');
      const bar=document.querySelector('.progress-fill');
      const animation=bar.getAnimations()[0];
      renderIndexProgress({messages:['[2/3] Checking b.py','Text embeddings /private/notes/b.py: 28 passages']},1,1,'/tmp/notes');
      const result={sameBar:bar===document.querySelector('.progress-fill'),sameAnimation:animation===bar.getAnimations()[0],message:document.querySelector('.index-message').textContent};
      document.querySelector('#indexing').innerHTML='';
      return result;
    });
    assert.equal(progress.sameBar,true);
    assert.equal(progress.sameAnimation,true);
    assert.equal(progress.message,'Preparing search for b.py');
    const folderProgress=await page.evaluate(async()=>{
      const {renderIndexProgress}=await import('./app.js');
      renderIndexProgress({messages:[],progress:{completed:1,total:2,revision:1,stage:'Creating search embeddings',file:'/tmp/notes/b/two.py',folders:[{path:'.',completed:1,total:2,failed:0},{path:'a',completed:1,total:1,failed:0},{path:'b',completed:0,total:1,failed:0}]}},1,1,'/tmp/notes');
      const result={width:document.querySelector('.progress-fill').style.width,rows:document.querySelectorAll('.folder-progress-row').length,label:document.querySelector('.index-count').textContent};
      document.querySelector('#indexing').innerHTML='';return result;
    });
    assert.equal(folderProgress.width,'50%');
    assert.equal(folderProgress.rows,2);
    assert.equal(folderProgress.label,'1 / 2 files complete');

    const addedFile=path.join(dir,'Fresh thought.txt');
    fs.writeFileSync(addedFile,'A fresh thought about semantic retrieval.');
    await desktop.evaluate(({dialog},chosen)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[chosen]});},addedFile);
    await clickMenu('add-files');
    await expect.poll(()=>page.locator('#file-count').textContent(),{timeout:60000}).toBe('5');
    const liveFolder=path.join(dir,'Live indexing');
    fs.mkdirSync(path.join(liveFolder,'nested'),{recursive:true});
    fs.writeFileSync(path.join(liveFolder,'a.py'),'def ready_first(): return 1');
    fs.writeFileSync(path.join(liveFolder,'nested','b.py'),Array.from({length:300},(_,i)=>`def item_${i}(): return ${i}`).join('\n'));
    await page.evaluate(()=>{
      window.liveCounts=[];
      new MutationObserver(()=>window.liveCounts.push(document.querySelector('#file-count').textContent)).observe(document.querySelector('#file-count'),{childList:true,subtree:true});
    });
    await desktop.evaluate(({dialog},chosen)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[chosen]});},liveFolder);
    await page.locator('[data-collection="0"]').click();
    await expect.poll(()=>desktop.evaluate(({Menu})=>Menu.getApplicationMenu().getMenuItemById('add-folder').enabled)).toBe(true);
    await clickMenu('add-folder');
    await expect.poll(()=>page.locator('[data-view="home"]').getAttribute('aria-current')).toBe('page');
    await expect.poll(()=>desktop.evaluate(({Menu})=>Menu.getApplicationMenu().getMenuItemById('index-progress').enabled)).toBe(true);
    await clickMenu('index-progress');
    await expect.poll(()=>page.locator('#indexing details').evaluate(node=>node.open)).toBe(true);

    await expect.poll(()=>page.locator('#file-count').textContent(),{timeout:60000}).toBe('7');
    const liveCounts=await page.evaluate(()=>window.liveCounts);
    assert.ok(liveCounts.includes('6'),'First file should appear before the larger second file finishes');
    await expect.poll(()=>page.locator('#indexing .index-card').count()).toBe(0);
    const engine = await page.evaluate(()=>window.recall.engineStatus());
    assert.equal(engine.channels.text,'ready');
    assert.equal(engine.channels.document,'ready');
    assert.equal(engine.channels.scene,'ready');
    fs.writeFileSync('/tmp/recall-desktop-warmup.json',JSON.stringify(engine,null,2));
    await page.locator('[data-appearance="light"]').click();
    await expect.poll(()=>launcher.locator('html').getAttribute('data-theme')).toBe('light');
    await page.emulateMedia({colorScheme:'dark'});
    await page.locator('[data-appearance="system"]').click();
    await expect.poll(()=>page.locator('html').getAttribute('data-theme')).toBe('dark');
    await page.emulateMedia({colorScheme:'light'});
    await expect.poll(()=>page.locator('html').getAttribute('data-theme')).toBe('light');
    await page.locator('[data-collection="0"]').click();
    await desktop.evaluate(({dialog})=>{dialog.showMessageBox=async()=>({response:0});});
    await page.locator('[data-remove-collection="0"]').focus();
    await page.locator('[data-remove-collection="0"]').click();
    await expect.poll(()=>page.locator('[data-remove-collection="0"]').isDisabled()).toBe(false);
    assert.equal(await page.locator('#file-count').textContent(),'7');
    await desktop.evaluate(({dialog})=>{dialog.showMessageBox=async()=>({response:1});});
    await expect.poll(()=>desktop.evaluate(({Menu})=>Menu.getApplicationMenu().getMenuItemById('remove').enabled)).toBe(true);
    await clickMenu('remove');
    await expect.poll(()=>page.locator('#file-count').textContent()).toBe('0');
    await expect.poll(()=>launcher.locator('.file-row').count()).toBe(0);
    assert.equal(await page.locator('[data-collection]').count(),0);
    assert.equal(await page.locator('[data-view="home"]').getAttribute('aria-current'),'page');
    assert.equal(fs.existsSync(addedFile),true);
    assert.equal(fs.existsSync(path.join(dir,'Field notes','Field notes.pdf')),true);
    assert.deepEqual(errors,[]);
  } finally { await desktop.close(); fs.rmSync(dir,{recursive:true,force:true}); }
});
